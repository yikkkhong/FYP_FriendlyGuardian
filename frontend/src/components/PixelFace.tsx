export const PixelFace: React.FC<PixelFaceProps> = ({ emotion }) => {
  const pattern = FACE_PATTERNS[emotion] || FACE_PATTERNS.NEUTRAL;
  const theme = COLOR_THEMES[emotion] || COLOR_THEMES.NEUTRAL;

  return (
    <div
      style={{
        width: "320px",
        height: "320px",
        backgroundColor: theme.bg,
        borderRadius: "36px",
        padding: "24px",
        display: "grid",
        gridTemplateColumns: "repeat(16, 1fr)",
        gridTemplateRows: "repeat(16, 1fr)",
        gap: "4px",
        boxShadow: `0 0 50px ${theme.glow}`,
        border: `3px solid ${theme.active}`,
        transition: "all 0.4s cubic-bezier(0.4, 0, 0.2, 1)",
        boxSizing: "border-box",
      }}
    >
      {pattern.flatMap((row, rowIndex) =>
        row.map((pixel, colIndex) => (
          <div
            key={`${rowIndex}-${colIndex}`}
            style={{
              backgroundColor: pixel === 1 ? theme.active : "transparent",
              borderRadius: "2px",
              boxShadow: pixel === 1 ? `0 0 8px ${theme.active}` : "none",
              transition: "background-color 0.2s ease",
            }}
          />
        )),
      )}
    </div>
  );
};
